<?php

namespace app\Models;

class BeamType
{
    public $name;
    public $beamClass;
    public $fb;
    public $fs;
    public $E;
    public $fbW;
    public $fsW;
    public $EW;

    public function __construct($name, $fb, $fs, $E, $fbW, $fsW, $EW, $beamClass)
    {
        $this->name = $name;
        $this->fb = $fb;
        $this->fs = $fs;
        $this->E = $E;
        $this->fbW = $fbW;
        $this->fsW = $fsW;
        $this->EW = $EW;
        $this->beamClass = $beamClass;
    }
}

class BeamSize
{
    public $size;
    public $selfWt;
    public $b;
    public $d;
    public $A;
    public $Z;
    public $I;
    public $bT;
    public $dT;


    public function __construct($size, $selfWt, $b, $d, $A, $Z, $I, $bT = null, $dT = null)
    {
        $this->size = $size;
        $this->selfWt = $selfWt;
        $this->b = $b;
        $this->d = $d;
        $this->A = $A;
        $this->Z = $Z;
        $this->I = $I;
        $this->bT = $bT;
        $this->dT = $dT;
    }
}

